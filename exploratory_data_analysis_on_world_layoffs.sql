FROM layoffs_staging2
GROUP BY company
ORDER BY 2 DESC;


-- CONCLUDING DATASET INCLUDES LAYOFFS BETWEEN RESULT OF THE QUERY
SELECT MIN(`date`), MAX(`date`)
