-- ALMOST 3 YEARS BETWEEN MARCH 2020 AND MARCH 2023 AROUND AND AFTERMATH OF COVID


-- CHECKING WHICH INDUSTRIES GOT HIT THE WORST
SELECT industry, SUM(total_laid_off)
FROM layoffs_staging2
GROUP BY industry
ORDER BY 2 DESC;



-- SEEMS LIKE MOST PEOPLE LAID OFF FROM UNITED STATES
-- WHILE WE CAN CONCLUDE US HAD INFLATED EMPLOYMENT AND THEM HANDLING THE WAY THAT THEY DID LED TO THOSE NUMBERS
-- WE CAN ALSO CONCLUDE COLLECTED DATA WAS BIASED TOWARDS US WHICH CAN EXPLAIN THE HUGE DISCREPANCY BETWEEN THE NUMBERS
-- BIAS CAN BE CAUSED BY POLITICAL VIEWS BUT ITS MORE LIKELY THAT US HAD MUCH MORE PUBLICLY AND EASILY AVAILABLE DATA
